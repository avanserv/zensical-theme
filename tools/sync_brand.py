"""Vendor the avanserv brand artefacts into the theme package.

This repository is public and avanserv/brand is private, so the theme cannot depend on it and
copies what it needs instead (brand/docs/policy/consuming.md). Everything under
``assets/avanserv/brand/``, the favicons, ``assets/avanserv/tokens.css`` and the two mark
partials are written here and nowhere else: edit the brand, bump ``BRAND_VERSION`` and re-run.

``--check`` regenerates into a temporary tree and fails on any difference. It skips with a
warning, never a pass, when the brand checkout is missing, so a CI run without access says so.
"""

from __future__ import annotations

import argparse
import filecmp
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME = ROOT / "src" / "avanserv_zensical_theme"
PINNED = (ROOT / "BRAND_VERSION").read_text().strip()

# Destination, relative to THEME, for each artefact taken from the brand checkout.
VERBATIM = {
    "dist/fonts/spline-sans-latin.woff2": "assets/avanserv/brand/fonts/spline-sans-latin.woff2",
    "dist/fonts/spline-sans-latin-ext.woff2": (
        "assets/avanserv/brand/fonts/spline-sans-latin-ext.woff2"
    ),
    "dist/fonts/spline-sans-mono-latin.woff2": (
        "assets/avanserv/brand/fonts/spline-sans-mono-latin.woff2"
    ),
    "dist/fonts/spline-sans-mono-latin-ext.woff2": (
        "assets/avanserv/brand/fonts/spline-sans-mono-latin-ext.woff2"
    ),
    "fonts/OFL.txt": "assets/avanserv/brand/fonts/OFL.txt",
    "fonts/OFL-spline-sans-mono.txt": "assets/avanserv/brand/fonts/OFL-spline-sans-mono.txt",
    "dist/web/favicon.svg": "assets/avanserv/brand/favicon.svg",
    "dist/web/favicon.ico": "assets/avanserv/brand/favicon.ico",
    "dist/web/apple-touch-icon.png": "assets/avanserv/brand/apple-touch-icon.png",
}
HEADED = {
    "dist/fonts.css": "assets/avanserv/brand/fonts.css",
    "dist/base.css": "assets/avanserv/brand/base.css",
}

THEME_KEYS = re.compile(
    r"^--(font-(sans|mono)|text-[a-z0-9-]+|tracking-[a-z]+|radius-[a-z]+|shadow-[a-z]+"
    r"|transition-duration-[a-z]+|ease-[a-z]+)$"
)
RELATIVE = re.compile(r"oklch\(\s*from var\((--[a-z0-9-]+)\) l c h / ([0-9.]+)\s*\)")


def header(comment_open: str = "/*", comment_close: str = "*/") -> str:
    return f"{comment_open} Brand-Source: avanserv/brand@{PINNED} {comment_close}\n"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def strip_comments(css: str) -> str:
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def declarations(block: str) -> dict[str, str]:
    out = {}
    for name, value in re.findall(r"(--[a-z0-9*-]+)\s*:\s*([^;]+);", block):
        out[name] = " ".join(value.split())
    return out


def block(css: str, selector: str) -> str:
    start = css.index(selector + " {") + len(selector) + 2
    depth, i = 1, start
    while depth:
        depth += {"{": 1, "}": -1}.get(css[i], 0)
        i += 1
    return css[start : i - 1]


def colour(entry: dict) -> str:
    hex_ = entry["hex"]
    if entry["alpha"] == 1:
        return hex_
    r, g, b = (int(hex_[i : i + 2], 16) for i in (1, 3, 5))
    return f"rgb({r} {g} {b} / {entry['alpha']:g})"


def resolve(value: str, palette: dict, scope: str) -> str:
    """Flatten brand's relative-colour syntax, which browsers older than 2024 drop silently."""

    def sub(match: re.Match[str]) -> str:
        base = dict(palette[match.group(1)][scope])
        base["alpha"] = float(match.group(2))
        return colour(base)

    return RELATIVE.sub(sub, value)


def tokens_css(brand: Path) -> str:
    palette = json.loads((brand / "dist/tokens/palette.json").read_text())
    css = strip_comments((brand / "dist/tokens.css").read_text())
    theme = {
        k: v for k, v in declarations(block(css, "@theme static")).items() if THEME_KEYS.match(k)
    }
    chrome = {
        "light": declarations(block(css, ":root")),
        "dark": declarations(block(css, ".brand-dark")),
    }
    chrome_keys = ("--sb-track", "--sb-thumb", "--sb-thumb-hover", "--selection-bg")

    lines = [
        header(),
        "/* GENERATED by tools/sync_brand.py from dist/tokens/palette.json and dist/tokens.css. */",
        "",
        ':root,\n[data-md-color-scheme="default"] {',
        "  color-scheme: light;",
    ]
    lines += [f"  {k}: {colour(v['light'])};" for k, v in sorted(palette.items())]
    # Channel triplets of the ink ramp, for Zensical's search dialog, which composes
    # rgb(var(--x) / alpha) itself and so cannot take a hex value.
    lines += [
        f"  {k}-rgb: {' '.join(str(int(v['light']['hex'][i : i + 2], 16)) for i in (1, 3, 5))};"
        for k, v in sorted(palette.items())
        if k.startswith("--color-ink-")
    ]
    lines += [f"  {k}: {resolve(chrome['light'][k], palette, 'light')};" for k in chrome_keys]
    lines += [f"  {k}: {v};" for k, v in theme.items()]
    lines += ["}", "", '[data-md-color-scheme="slate"] {', "  color-scheme: dark;"]
    lines += [
        f"  {k}: {colour(v['dark'])};"
        for k, v in sorted(palette.items())
        if v["dark"] != v["light"]
    ]
    lines += [
        f"  {k}: {resolve(chrome['dark'][k], palette, 'dark')};"
        for k in chrome_keys
        if k in chrome["dark"]
    ]
    lines += ["}", ""]
    return "\n".join(lines)


def mark(geometry: dict, solid: bool) -> str:
    view_box = geometry["viewBox"]["regular"]
    if solid:
        paint = 'fill="currentColor" stroke="none"'
    else:
        # Heavy, not regular: the header and footer both draw the mark under 44px.
        paint = (
            f'fill="none" stroke="currentColor" stroke-width="{geometry["stroke"]["heavy"]}" '
            'stroke-linejoin="round" stroke-linecap="round" '
            f'stroke-dasharray="{geometry["dasharray"]}"'
        )
    return (
        f"{{#- Brand-Source: avanserv/brand@{PINNED}. GENERATED by tools/sync_brand.py. -#}}\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}" class="av-mark" '
        f'aria-hidden="true" focusable="false"><path {paint} d="{geometry["path"]}"/></svg>\n'
    )


def checkout_version(brand: Path) -> str | None:
    try:
        return subprocess.run(
            ["git", "-C", str(brand), "describe", "--tags", "--exact-match"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None


def sync(brand: Path, theme: Path) -> None:
    upstream = json.loads((brand / "dist/manifest.json").read_text())["artefacts"]
    record: dict[str, dict] = {}

    for source, dest in {**VERBATIM, **HEADED}.items():
        target = theme / dest
        target.parent.mkdir(parents=True, exist_ok=True)
        if source in HEADED:
            target.write_text(header() + (brand / source).read_text())
        else:
            shutil.copyfile(brand / source, target)
        key = source.removeprefix("dist/")
        record[dest] = {
            "source": source,
            "sha256": upstream[key]["sha256"] if key in upstream else sha256(brand / source),
            "headed": source in HEADED,
        }

    (theme / "assets/avanserv/tokens.css").write_text(tokens_css(brand))
    geometry = json.loads((brand / "dist/mark.geometry.json").read_text())
    (theme / "partials").mkdir(exist_ok=True)
    (theme / "partials/av-mark.html").write_text(mark(geometry, solid=False))
    (theme / "partials/av-mark-solid.html").write_text(mark(geometry, solid=True))

    manifest = {"brand": PINNED, "path": geometry["path"], "files": record}
    (theme / "assets/avanserv/brand/manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    )


GENERATED = (
    "assets/avanserv/brand",
    "assets/avanserv/tokens.css",
    "partials/av-mark.html",
    "partials/av-mark-solid.html",
)


def check(brand: Path) -> int:
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp)
        sync(brand, fresh)
        drift = []
        for rel in GENERATED:
            a, b = THEME / rel, fresh / rel
            if a.is_dir() or b.is_dir():
                cmp = filecmp.dircmp(a, b)
                stack = [(cmp, rel)]
                while stack:
                    c, prefix = stack.pop()
                    drift += [f"{prefix}/{n}" for n in c.left_only + c.right_only + c.diff_files]
                    stack += [(sub, f"{prefix}/{n}") for n, sub in c.subdirs.items()]
            elif not a.exists() or a.read_bytes() != b.read_bytes():
                drift.append(rel)
    if drift:
        print("brand-check: vendored files differ from avanserv/brand@" + PINNED, file=sys.stderr)
        for path in sorted(drift):
            print(f"  {path}", file=sys.stderr)
        print("Run `make sync-brand` and commit the result.", file=sys.stderr)
        return 1
    print(f"brand-check: vendored files match avanserv/brand@{PINNED}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Vendor the avanserv brand artefacts.")
    parser.add_argument("--check", action="store_true", help="fail on drift, write nothing")
    args = parser.parse_args()

    brand = Path(os.environ.get("BRAND_DIR", ROOT.parent / "brand")).resolve()
    if not (brand / "dist/manifest.json").is_file():
        if args.check:
            print(f"::warning::brand-check skipped: avanserv/brand not reachable at {brand}")
            return 0
        print(f"avanserv/brand checkout not found at {brand}; set BRAND_DIR", file=sys.stderr)
        return 1

    version = checkout_version(brand)
    if version != PINNED:
        print(
            f"{brand} is at {version or 'an untagged commit'}, BRAND_VERSION pins {PINNED}",
            file=sys.stderr,
        )
        return 1

    if args.check:
        return check(brand)
    sync(brand, THEME)
    print(f"Vendored avanserv/brand@{PINNED} into {THEME.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
